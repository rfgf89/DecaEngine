	/// <summary>Finds a "Base" preset matching all three colors exactly.</summary>
	public static BasePreset? FindMatchingBasePreset(Vector4 accent, Vector4 background, Vector4 surface)
	{
		foreach (var preset in BasePresets)
		{
			if (preset.Accent == accent && preset.Background == background && preset.Surface == surface)
			{
				return preset;
			}
		}

		return null;
	}

