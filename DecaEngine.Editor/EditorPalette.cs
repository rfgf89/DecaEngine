	/// <summary>Relative luminance of a color (0..1), used to check contrast between text and background.</summary>
	public static float Luminance(Vector4 color) => 0.299f * color.X + 0.587f * color.Y + 0.114f * color.Z;

	/// <summary>??????????? ??????? ??????? (0..1), ??? ??????? Text/Selection ????????? ??????????
	/// ???????????? ? ???????? Background - ??. <see cref="HasSufficientContrast"/>.</summary>
	public const float MinContrastLuminanceDelta = 0.35f;

	/// <summary>
	/// true, ???? <paramref name="color"/> (Text ??? Selection) ?????????? ?????????? ?
	/// <paramref name="background"/>, ????? ?? "????????" ? UI - ????????, ??????? Text-?????? ??
	/// ??????? Base-???????. ???????????? ? Preferences ? Appearance, ????? ????????? (???????????
	/// ??? ??????) ???????? ?????????? ?????????? ???????? ?????? ????, ????? ?????? ????????? ??
	/// ? ???????? ??????????? ? ????? ?????????.
	/// </summary>
	public static bool HasSufficientContrast(Vector4 color, Vector4 background) =>
		MathF.Abs(Luminance(color) - Luminance(background)) >= MinContrastLuminanceDelta;
