	/// <summary>???? ??????? <see cref="Text"/> ???????????? ?????????? ? ???????? <see cref="Background"/>
	/// (??. <see cref="HasSufficientContrast"/>), ??????????? ??? ?? Text-?????? ? ??????????
	/// ?????????? ? Background - ??. ??????????? ? <see cref="ApplyBasePreset"/>.</summary>
	private static void EnsureTextContrast()
	{
		if (HasSufficientContrast(Text, Background))
		{
			return;
		}

		TextPreset? best = null;
		var bestContrast = -1f;
		foreach (var preset in TextPresets)
		{
			var contrast = MathF.Abs(Luminance(preset.Text) - Luminance(Background));
			if (contrast > bestContrast)
			{
				bestContrast = contrast;
				best = preset;
			}
		}

		if (best.HasValue)
		{
			ApplyTextPreset(best.Value);
		}
	}

	/// <summary>?? ?? ?????, ??? <see cref="EnsureTextContrast"/>, ?? ??? <see cref="Selection"/>
	/// ? <see cref="SelectionPresets"/>.</summary>
	private static void EnsureSelectionContrast()
	{
		if (HasSufficientContrast(Selection, Background))
		{
			return;
		}

		SelectionPreset? best = null;
		var bestContrast = -1f;
		foreach (var preset in SelectionPresets)
		{
			var contrast = MathF.Abs(Luminance(preset.Selection) - Luminance(Background));
			if (contrast > bestContrast)
			{
				bestContrast = contrast;
				best = preset;
			}
		}

		if (best.HasValue)
		{
			ApplySelectionPreset(best.Value);
		}
	}

