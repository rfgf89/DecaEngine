	public static Vector4 WithAlpha(Vector4 color, float alpha) => new(color.X, color.Y, color.Z, alpha);

	public static Vector4 Lighten(Vector4 color, float amount) => new(
		Math.Clamp(color.X + amount, 0f, 1f),
		Math.Clamp(color.Y + amount, 0f, 1f),
		Math.Clamp(color.Z + amount, 0f, 1f),
		color.W);

	public static Vector4 Darken(Vector4 color, float amount) => Lighten(color, -amount);

