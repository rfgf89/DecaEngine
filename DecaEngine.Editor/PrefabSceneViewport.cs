	/// <summary>
	/// ?????????? ?????? 3D-???????????? ???????? ???????, ???????????? ? <see cref="InspectorWindow"/>.
	/// ?? ?????????? GPU render target/pipeline ?????? (??? ??????????? ?? ??????????? ???????? ?????,
	/// ?????????? ?????? ?????/?????????? ? ?.?.), ? ?????? ????? ?????? ?????? ???????? ? ???? ????
	/// (???????/???????/??????? = ??????? TRS-??????? ????????) ????? ?????????? ????????? ImGuizmo
	/// (<see cref="ImGuizmo.DrawGrid"/> / <see cref="ImGuizmo.DrawCubes"/>), ???? ??????-?????? ????? ?
	/// ??????????? gizmo ???????????/????????/??????????????? ????????? ????????
	/// (<see cref="ImGuizmo.Manipulate"/>), ????????? ???????? ???????????? ??????? ?
	/// Position/Rotation/Scale3 ????????.
	/// </summary>
	public class PrefabSceneViewport
	{
		private Vector3 _target = Vector3.Zero;
		private float _yaw = -0.6f;
		private float _pitch = 0.35f;
		private float _distance = 8f;
		private bool _orbiting;
		private bool _panning;

		public ImGuizmoOperation Operation { get; set; } = ImGuizmoOperation.Translate;

		public void FrameAll(Entity root)
		{
			_target = root.HasPosition ? root.Position.value : Vector3.Zero;
			_distance = 8f;
			_yaw = -0.6f;
			_pitch = 0.35f;
		}

		/// <summary>?????? ??????? ? ??????? ??????? ??????? ImGui ? ???????? ????????.</summary>
		/// <returns>true, ???? ????????? ???????? ???? ???????? ????? gizmo (???????/???????/???????).</returns>
		public bool Render(Entity root, Entity? selected, Vector2 size)
		{
			if (size.X <= 1f || size.Y <= 1f)
			{
				return false;
			}

			var cursor = ImGui.GetCursorScreenPos();

			// ?????: ?? ?????????? InvisibleButton/????? ?????? ImGui-????? ?????? ??????? gizmo.
			// ImGuizmo ?????? ???? ??????, ????? ?? ?????? ??????????????, ????? ???? ???????
			// CanActivate(), ??????? ??????? !ImGui.IsAnyItemHovered() && !ImGui.IsAnyItemActive().
			// InvisibleButton ?????????????? ??? hoverable item ? "?????????????" hover ?? ????,
			// ??-?? ???? ImGuizmo ??????? ???? ?????????? ?? ?????? ?????? ? ??????? ?? ??????????
			// ??????????? (????????? ??? ???? ??? ???????? ????????? - ?????? ??????? ??? ?????????
			// ?? ????). Dummy() ??????????? ????? ? layout, ?? ?? ???????????? hoverable item.
			ImGui.Dummy(size);
			bool hovered = ImGui.IsWindowHovered(ImGuiHoveredFlags.ChildWindows) && ImGui.IsMouseHoveringRect(cursor, cursor + size);

			HandleCameraInput(hovered);

			var eye = _target + _distance * new Vector3(
				MathF.Cos(_pitch) * MathF.Sin(_yaw),
				MathF.Sin(_pitch),
				MathF.Cos(_pitch) * MathF.Cos(_yaw));

			var view = Matrix4x4.CreateLookAt(eye, _target, Vector3.UnitY);
			float aspect = size.X / size.Y;
			var proj = Matrix4x4.CreatePerspectiveFieldOfView(60f * (MathF.PI / 180f), aspect, 0.05f, 500f);

			var drawList = ImGui.GetWindowDrawList();

			// ??? ????? ?????? ???? (???????? ? drawlist ???????? ????), ????? ??????? ????????
			// ???? ????? ????????? ?????????? ?? ????, ??? ?????? ImGuizmo.
			drawList.AddRectFilled(cursor, cursor + size, ImGui.GetColorU32(new Vector4(0.06f, 0.06f, 0.07f, 1f)));

			// ??????? ??????? ?????: BeginFrame() ??????? ??????????? fullscreen invisible-????
			// ? (????)????????????? ?????????? draw list ?? ????, ??????? SetDrawlist()/SetRect()
			// ????? ????? ????? BeginFrame(), ????? ?? ???????? ??? drawlist ? ??? ???????? "? ??????".
			ImGuizmo.SetImGuiContext(ImGui.GetCurrentContext());
			ImGuizmo.SetOrthographic(false);
			ImGuizmo.BeginFrame();
			ImGuizmo.SetDrawlist(drawList);
			ImGuizmo.SetRect(cursor.X, cursor.Y, size.X, size.Y);

			var identity = Matrix4x4.Identity;
			ImGuizmo.DrawGrid(ref view, ref proj, ref identity, 10f);

			var matrices = CollectWorldMatrices(root);
			if (matrices.Count > 0)
			{
				var array = matrices.ToArray();
				ImGuizmo.DrawCubes(ref view, ref proj, array, array.Length);
			}

			drawList.AddText(cursor + new Vector2(6f, 4f), ImGui.GetColorU32(new Vector4(1f, 1f, 1f, 0.6f)),
				$"cubes: {matrices.Count}  dist: {_distance:0.0}  yaw: {_yaw:0.00}  pitch: {_pitch:0.00}");

			bool changed = false;

			if (selected.HasValue && !selected.Value.IsNull)
			{
				var world = ComputeWorldMatrix(selected.Value);
				if (ImGuizmo.Manipulate(ref view, ref proj, Operation, ImGuizmoMode.Local, ref world))
				{
					ApplyWorldMatrix(selected.Value, world);
					changed = true;
				}
			}

			return changed;
		}

		private void HandleCameraInput(bool hovered)
		{
			var io = ImGui.GetIO();

			if (hovered && ImGui.IsMouseClicked(ImGuiMouseButton.Right))
			{
				_orbiting = true;
			}
			if (_orbiting && ImGui.IsMouseReleased(ImGuiMouseButton.Right))
			{
				_orbiting = false;
			}

			if (hovered && ImGui.IsMouseClicked(ImGuiMouseButton.Middle))
			{
				_panning = true;
			}
			if (_panning && ImGui.IsMouseReleased(ImGuiMouseButton.Middle))
			{
				_panning = false;
			}

			if (_orbiting)
			{
				var delta = io.MouseDelta;
				_yaw -= delta.X * 0.01f;
				_pitch = Math.Clamp(_pitch - delta.Y * 0.01f, -1.5f, 1.5f);
			}
			else if (_panning)
			{
				var delta = io.MouseDelta;
				var right = new Vector3(MathF.Cos(_yaw), 0f, -MathF.Sin(_yaw));
				var panScale = MathF.Max(0.05f, _distance * 0.001f);
				_target -= right * delta.X * panScale;
				_target += Vector3.UnitY * delta.Y * panScale;
			}

			if (hovered && io.MouseWheel != 0f)
			{
				_distance = Math.Clamp(_distance - io.MouseWheel * _distance * 0.1f, 0.5f, 500f);
			}
		}

		private static List<Matrix4x4> CollectWorldMatrices(Entity entity)
		{
			var list = new List<Matrix4x4>();
			Collect(entity, list);
			return list;
		}

		private static void Collect(Entity entity, List<Matrix4x4> list)
		{
			list.Add(ComputeWorldMatrix(entity));
			foreach (var child in entity.ChildEntities)
			{
				Collect(child, list);
			}
		}

		private static Matrix4x4 ComputeWorldMatrix(Entity entity)
		{
			var local = LocalMatrix(entity);
			var parent = entity.Parent;
			return parent.IsNull ? local : local * ComputeWorldMatrix(parent);
		}

		private static Matrix4x4 LocalMatrix(Entity entity)
		{
			Vector3 pos = entity.HasPosition ? entity.Position.value : Vector3.Zero;
			Quaternion rot = entity.HasRotation ? entity.Rotation.value : Quaternion.Identity;
			Vector3 scale = entity.HasScale3 ? entity.Scale3.value : Vector3.One;
			return DecaEngine.Graphics.Diligent.MathUtils.CreateTrs(pos, rot, scale);
		}

		private static void ApplyWorldMatrix(Entity entity, Matrix4x4 world)
		{
			var parent = entity.Parent;
			var local = world;
			if (!parent.IsNull)
			{
				var parentWorld = ComputeWorldMatrix(parent);
				if (Matrix4x4.Invert(parentWorld, out var parentInv))
				{
					local = world * parentInv;
				}
			}

			if (!Matrix4x4.Decompose(local, out var scale, out var rotation, out var translation))
			{
				return;
			}

			if (!entity.HasPosition)
			{
				entity.AddComponent<Position>();
			}
			entity.Position = new Position(translation.X, translation.Y, translation.Z);

			if (!entity.HasRotation)
			{
				entity.AddComponent<Rotation>();
			}
			entity.Rotation = new Rotation { value = rotation };

			if (!entity.HasScale3)
			{
				entity.AddComponent<Scale3>();
			}
			entity.Scale3 = new Scale3(scale.X, scale.Y, scale.Z);
		}
	}
