using System.Text.Json;
using System.Text.Json.Serialization;

namespace DecaEngine.Editor
{
	/// <summary>
	/// ???????????? ??????? ?????????: ???, ?????? ? ?????? ??????????. ???????? ? ?????
	/// "project.json" ? ????? ???????? ??????? (????? ? .csproj) ? ????????????? ?
	/// <see cref="ProjectWindow"/>, ??????? ???????? ?????? ?? ???????????? ???????, ? ?? ??
	/// ??? ??????/?????? (??. <see cref="ProjectSession"/>).
	/// </summary>
	public class ProjectConfig
	{
		private const string FileName = "project.json";

		private static readonly JsonSerializerOptions SerializerOptions = new()
		{
			WriteIndented = true
		};

		public string Name { get; set; } = "New Project";

		public string Version { get; set; } = "1.0.0";

		/// <summary>???? ? ?????? ???????, ???????????? ???????? ??????? (??? ??????????).</summary>
		public string? IconPath { get; set; }

		[JsonIgnore]
		public string ProjectDirectory { get; private set; } = string.Empty;

		public static ProjectConfig Load(string projectDirectory)
		{
			var path = Path.Combine(projectDirectory, FileName);

			try
			{
				if (File.Exists(path))
				{
					var json = File.ReadAllText(path);
					var loaded = JsonSerializer.Deserialize<ProjectConfig>(json);
					if (loaded is not null)
					{
						loaded.ProjectDirectory = projectDirectory;
						return loaded;
					}
				}
			}
			catch
			{
				// ????????????/?????????? ???? ???????????? ? ?????????? ???????? ?? ?????????,
				// ?? ???????? ?????? ?????????.
			}

			return new ProjectConfig
			{
				Name = Path.GetFileName(projectDirectory.TrimEnd(Path.DirectorySeparatorChar, Path.AltDirectorySeparatorChar)),
				ProjectDirectory = projectDirectory
			};
		}

		public bool Save()
		{
			if (string.IsNullOrEmpty(ProjectDirectory))
			{
				return false;
			}

			try
			{
				Directory.CreateDirectory(ProjectDirectory);
				var path = Path.Combine(ProjectDirectory, FileName);
				var json = JsonSerializer.Serialize(this, SerializerOptions);
				File.WriteAllText(path, json);
				return true;
			}
			catch
			{
				return false;
			}
		}
	}
}

