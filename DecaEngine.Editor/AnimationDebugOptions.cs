using System.Text.Json.Serialization;

namespace DecaEngine.Editor;

/// <summary>
/// Что именно показывать в дебаге анимации. Отдельная структура, а не набор булей в драйвере:
/// её читают и драйвер, и окно дебага, и настройки редактора, и держать источником правды поля
/// драйвера значило бы, что окно не может показать состояние до появления первого персонажа.
///
/// Всё выключено по умолчанию: дебаг-вид - это ИНСТРУМЕНТ, который включают под вопрос, а не
/// украшение вьюпорта. Единственное исключение - <see cref="OnTop"/>, но это не слой, а способ
/// рисовать остальные.
/// </summary>
public struct AnimationDebugOptions()
{
	/// <summary>Скелет октаэдрами по костям - основной вид.</summary>
	public bool Skeleton = false;

	/// <summary>Оси каждого сустава (X красная, Y зелёная, Z синяя). Именно они показывают перекрут
	/// кости вокруг собственной оси - ошибку, невидимую на «палочках» скелета.</summary>
	public bool JointAxes = false;

	/// <summary>Имена костей подписями поверх вьюпорта. Отдельно от <see cref="JointAxes"/>: осями
	/// пользуются, чтобы понять ОРИЕНТАЦИЮ, а именами - чтобы заполнить поля компонентов, где кости
	/// задаются строками, и эти два вопроса задают в разное время.</summary>
	public bool JointNames = false;

	/// <summary>Bind-поза приглушённым цветом поверх текущей: так видно, НАСКОЛЬКО клип увёл
	/// скелет, и сразу отличима «поза не применилась» от «поза применилась, но не та».</summary>
	public bool BindPose = false;

	/// <summary>Цели и лучи foot IK: луч под стопой, точка попадания с нормалью, цель сустава.</summary>
	public bool FootIk = false;

	/// <summary>Цепочки spring bones - подсветкой поверх скелета.</summary>
	public bool SpringChains = false;

	/// <summary>Цель look-at и ось взгляда кости.</summary>
	public bool LookAt = false;

	/// <summary>Рисовать поверх геометрии, без депт-теста. Почти всегда именно так и надо: скелет
	/// целиком внутри меша, и с депт-тестом его не видно вовсе. Выключается, когда нужен обратный
	/// вопрос - «торчит ли кость наружу».</summary>
	public bool OnTop = true;

	/// <summary>Вычисляемое - в файл настроек не пишется: иначе при чтении старого файла оно
	/// оказалось бы «настройкой», противоречащей самим галочкам.</summary>
	[JsonIgnore]
	public bool AnyEnabled =>
		Skeleton || JointAxes || JointNames || BindPose || FootIk || SpringChains || LookAt;
}

/// <summary>Что показывать в дебаге физики. См. шапку <see cref="AnimationDebugOptions"/> о том,
/// почему это отдельная структура и почему всё выключено по умолчанию.</summary>
public struct PhysicsDebugOptions()
{
	/// <summary>Каркасы коллайдеров тел. Цвет кодирует состояние: динамика оранжевая, кинематика
	/// голубая, спящее тело серое - «почему оно не падает» и «почему оно проваливается» это разные
	/// вопросы, и различать их надо до того, как лезть в отладчик.</summary>
	public bool Colliders = false;

	/// <summary>
	/// Рисовать каркасы коллайдеров С депт-тестом. По умолчанию НЕТ, то есть поверх геометрии - как
	/// скелет в дебаге анимации (см. <see cref="AnimationDebugOptions.OnTop"/>) и по той же причине:
	/// коллайдер персонажа целиком ВНУТРИ его меша, и с депт-тестом его не видно вовсе. Вопрос
	/// «какого размера капсулы и совпадают ли они с телом» - самый частый к этой галочке, и по
	/// умолчанию она обязана на него отвечать, а не показывать пустой экран.
	///
	/// Отдельно от общего <see cref="OnTop"/>, потому что у остальных слоёв физики ответ ДРУГОЙ:
	/// статика сцены, контакты и лучи живут снаружи мешей, и «поверх всего» превращает их в
	/// нечитаемую сетку по всему экрану. Один флаг на шесть слоёв заставлял выбирать между «не видно
	/// капсул» и «не видно ничего».
	///
	/// Поле названо ОТ ОБРАТНОГО намеренно: полезное поведение обязано совпадать с нулевым
	/// значением. Структура читается из JSON, и объект без этого ключа (старый файл настроек - а он
	/// у всех такой, см. IncludeFields в EditorSettings) даёт ровно <c>default</c>. Поле
	/// «CollidersOnTop = true» в такой ситуации молча приезжало бы выключенным, то есть дефолт,
	/// написанный в коде, не действовал бы ни у кого.
	/// </summary>
	public bool CollidersDepthTested = false;

	/// <summary>Каркас статики сцены. Отдельно от тел: статика - это весь пол уровня, и включать её
	/// вместе с телами значит закрасить экран.</summary>
	public bool Statics = false;

	/// <summary>Точки контакта с нормалями (см. PhysicsContactRecorder). Сбор контактов стоит
	/// работы в узкой фазе, поэтому включается вместе с этой галочкой, а не постоянно.</summary>
	public bool Contacts = false;

	/// <summary>Лучи райкастов кадра - в первую очередь лучи foot IK.</summary>
	public bool Rays = false;

	/// <summary>Скорости тел стрелками.</summary>
	public bool Velocities = false;

	/// <summary>Связи рэгдолла: отрезок между центрами связанных тел и точка крепления сустава.</summary>
	public bool RagdollJoints = false;

	/// <summary>Рисовать без депт-теста ОСТАЛЬНЫЕ слои физики - статику, контакты, лучи, скорости,
	/// суставы. Выключено по умолчанию: всё это живёт снаружи мешей и с депт-тестом читается лучше.
	/// Коллайдеры сюда не входят, у них свой <see cref="CollidersDepthTested"/>.</summary>
	public bool OnTop = false;

	[JsonIgnore]
	public bool AnyEnabled => Colliders || Statics || Contacts || Rays || Velocities || RagdollJoints;

	/// <summary>Нужен ли сбор контактов в узкой фазе. Отдельным свойством, потому что это
	/// единственная галочка, которая стоит денег ДО отрисовки.</summary>
	[JsonIgnore]
	public bool NeedsContactRecording => Contacts;
}
