						new Vector2(center.X + half, center.Y),
						new Vector2(center.X - half * 0.6f, center.Y + half),
						arrowColor);
				}
			}

			DrawLabel(drawList, labelLines, screenPos, cellSize);
			ImGui.PopID();
		}

		private void DrawLabel(ImDrawListPtr drawList, IReadOnlyList<string> lines, Vector2 screenPos, float cellSize)
		{
			var textColor = ImGui.GetColorU32(ImGuiCol.Text);
			var lineHeight = ImGui.GetTextLineHeight();
			var y = screenPos.Y + cellSize;

			foreach (var line in lines)
			{
				var textSize = ImGui.CalcTextSize(line);
				var textPos = new Vector2(screenPos.X + (cellSize - textSize.X) * 0.5f, y);
				drawList.AddText(textPos, textColor, line);
				y += lineHeight;
			}
		}

		private static string TruncateToWidth(string text, float maxWidth)
		{
			if (ImGui.CalcTextSize(text).X <= maxWidth)
			{
				return text;
			}

			const string ellipsis = "...";
			var lo = 0;
			var hi = text.Length;

			while (lo < hi)
			{
				var mid = (lo + hi + 1) / 2;
				var candidate = text[..mid] + ellipsis;
				if (ImGui.CalcTextSize(candidate).X <= maxWidth)
				{
					lo = mid;
				}
				else
				{
					hi = mid - 1;
				}
			}

			return lo <= 0 ? ellipsis : text[..lo] + ellipsis;
		}

		/// <summary>
		/// ????????? ????? ?? ?????? ??????? ?? ????? <paramref name="maxWidth"/> ??? ???????
		/// ??????????? - ???????????? ??? ?????????? ?????? (??. RenderEntry), ??? ??? ?????? ????
		/// ????? ?????????. ??????? ????????? ?? ?????? (????????); ???? ????????? "?????" ???
		/// ????? ???? maxWidth (????????, ??????? ??? ????? ??? ????????) - ????? ??? ???????????.
		/// </summary>
		private static List<string> WrapTextToLines(string text, float maxWidth)
		{
			var lines = new List<string>();

			if (ImGui.CalcTextSize(text).X <= maxWidth)
			{
				lines.Add(text);
				return lines;
			}

			var words = text.Split(' ');
			var current = string.Empty;

			foreach (var word in words)
			{
				var candidate = current.Length == 0 ? word : current + " " + word;
				if (ImGui.CalcTextSize(candidate).X <= maxWidth)
				{
					current = candidate;
					continue;
				}

				if (current.Length > 0)
				{
					lines.Add(current);
				}

				var remaining = word;
				while (ImGui.CalcTextSize(remaining).X > maxWidth && remaining.Length > 1)
				{
					var lo = 1;
					var hi = remaining.Length;
					while (lo < hi)
					{
						var mid = (lo + hi + 1) / 2;
						if (ImGui.CalcTextSize(remaining[..mid]).X <= maxWidth)
						{
							lo = mid;
						}
						else
						{
							hi = mid - 1;
						}
					}

					lines.Add(remaining[..lo]);
					remaining = remaining[lo..];
				}

				current = remaining;
			}

			if (current.Length > 0)
			{
				lines.Add(current);
			}

			return lines;
		}

		private static bool IsPrefabJson(string fileName) =>
			fileName.EndsWith(".prefab.json", StringComparison.OrdinalIgnoreCase);

		private static bool IsPrefabBinary(string fileName) =>
			fileName.EndsWith(".prefab.bin", StringComparison.OrdinalIgnoreCase);

		private static bool IsGltfModel(string fileName) =>
			fileName.EndsWith(".gltf", StringComparison.OrdinalIgnoreCase) ||
			fileName.EndsWith(".glb", StringComparison.OrdinalIgnoreCase);

		// internal - reused by ComponentFieldEditor.DrawAssetRef to show the same file-type icon
		// on AssetRef fields as AssetBrowserWindow shows for the underlying file.
		internal static FileIconKind GetFileIconKind(string fileName)
		{
			if (IsPrefabJson(fileName) || IsPrefabBinary(fileName))
			{
				return FileIconKind.Prefab;
			}

			var ext = Path.GetExtension(fileName).ToLowerInvariant();

			return ext switch
			{
				".png" or ".jpg" or ".jpeg" or ".bmp" or ".tga" or ".gif" or ".dds" or ".ktx" or ".hdr" => FileIconKind.Image,
				".cs" or ".xaml" => FileIconKind.Code,
				".json" => FileIconKind.Json,
				".hlsl" or ".glsl" or ".fx" or ".shader" or ".vert" or ".frag" or ".comp" => FileIconKind.Shader,
				".wav" or ".mp3" or ".ogg" or ".flac" => FileIconKind.Audio,
				".obj" or ".fbx" or ".gltf" or ".glb" or ".dae" => FileIconKind.Model,
				".mat" => FileIconKind.Material,
				".scene" or ".prefab" => FileIconKind.Scene,
				_ => FileIconKind.Generic
			};
		}

