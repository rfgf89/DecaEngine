		private void CommitDeleteAsset()
		{
			var path = _deleteConfirmPath;
			_deleteConfirmPath = null;

			if (path is null)
			{
				return;
			}

			try
			{
				if (Directory.Exists(path))
				{
					Directory.Delete(path, true);
				}
				else if (File.Exists(path))
				{
					File.Delete(path);
				}

				if (string.Equals(_selectedPath, path, StringComparison.OrdinalIgnoreCase))
				{
					_selectedPath = null;
				}

				if (string.Equals(_clipboardPath, path, StringComparison.OrdinalIgnoreCase))
				{
					_clipboardPath = null;
				}
			}
			catch
			{
				// ???? ?????, ???????????? ???? ? ?.?. - ???? ??????????.
			}

			RefreshEntries();
		}

		private void PasteClipboard(string targetDirectory)
		{
			if (_clipboardPath is null)
			{
				return;
			}

			var sourcePath = _clipboardPath;
			var name = Path.GetFileName(sourcePath);
			var destination = MakeUniqueDestination(Path.Combine(targetDirectory, name));

			try
			{
				if (Directory.Exists(sourcePath))
				{
					if (_clipboardIsCut)
					{
						Directory.Move(sourcePath, destination);
					}
					else
					{
						CopyDirectoryRecursive(sourcePath, destination);
					}
				}
				else if (File.Exists(sourcePath))
				{
					if (_clipboardIsCut)
					{
						File.Move(sourcePath, destination);
					}
					else
					{
						File.Copy(sourcePath, destination);
					}
				}

				_selectedPath = destination;
			}
			catch
			{
				// ??????? ???? ?????, ???????????? ???? ? ?.?. - ???? ??????????.
			}

			if (_clipboardIsCut)
			{
				_clipboardPath = null;
			}

			RefreshEntries();
		}

		private static string MakeUniqueDestination(string destination)
		{
			if (!File.Exists(destination) && !Directory.Exists(destination))
			{
				return destination;
			}

			var directory = Path.GetDirectoryName(destination) ?? string.Empty;
			var extension = Path.GetExtension(destination);
			var nameWithoutExt = Path.GetFileNameWithoutExtension(destination);

			var index = 1;
			string candidate;
			do
			{
				candidate = Path.Combine(directory, $"{nameWithoutExt} ({index++}){extension}");
			}
			while (File.Exists(candidate) || Directory.Exists(candidate));

			return candidate;
		}

		private static void CopyDirectoryRecursive(string sourceDir, string destDir)
		{
			Directory.CreateDirectory(destDir);

			foreach (var file in Directory.GetFiles(sourceDir))
			{
				File.Copy(file, Path.Combine(destDir, Path.GetFileName(file)));
			}

			foreach (var subDir in Directory.GetDirectories(sourceDir))
			{
				CopyDirectoryRecursive(subDir, Path.Combine(destDir, Path.GetFileName(subDir)));
			}
		}

		private void CreatePrefab(string directory)
		{
			var path = Path.Combine(directory, "New Prefab.prefab.json");
			int index = 1;
			while (File.Exists(path))
			{
				path = Path.Combine(directory, $"New Prefab {index++}.prefab.json");
			}

			var store = new EntityStore();
			PrefabAsset.SaveJson(store.CreateEntity(), path);
			RefreshEntries();
			_inspectorWindow.ShowPrefab(path);
		}

		private void RefreshEntries()
		{
			_entries.Clear();

			if (_currentDirectory is null || !Directory.Exists(_currentDirectory))
			{
				return;
			}

			try
			{
				var directories = Directory.GetDirectories(_currentDirectory)
					.OrderBy(d => Path.GetFileName(d), StringComparer.OrdinalIgnoreCase);

				foreach (var dir in directories)
				{
					_entries.Add(new AssetEntry(dir, Path.GetFileName(dir), true, IsDirectoryEmpty(dir)));
				}

				var files = Directory.GetFiles(_currentDirectory)
					.OrderBy(f => Path.GetFileName(f), StringComparer.OrdinalIgnoreCase);

				var projectDirectory = _projectSession.ProjectDirectory;

				foreach (var file in files)
				{
					// Skip .prefab.bin files - they are compiled prefabs and shouldn't be displayed
					if (IsPrefabBinary(Path.GetFileName(file)))
					{
						continue;
					}

					var fileName = Path.GetFileName(file);
					_entries.Add(new AssetEntry(file, fileName, false, false));

					// Раскрытая модель: сразу за ней вкладываем её SubMesh-и как отдельные записи
					// (по манифесту запечённых иконок, см. ModelIconBaker/ModelIconCache).
					if (projectDirectory is null || !IsGltfModel(fileName) || !_expandedModels.Contains(file))
					{
						continue;
					}

					var manifest = _iconCache.GetManifest(projectDirectory, file);
					if (manifest is null)
					{
						continue;
					}

					for (int i = 0; i < manifest.SubMeshNames.Count; i++)
					{
						_entries.Add(new AssetEntry(file, manifest.SubMeshNames[i], i));
					}
				}
			}
			catch
			{
				// ????? ????? ?????????/????? ??????????? ????? ??????? ? ?????? ??????? ?????? ??????.
			}
		}

		private static bool IsDirectoryEmpty(string path)
		{
			try
			{
				return !Directory.EnumerateFileSystemEntries(path).Any();
			}
			catch
			{
				return true;
			}
		}

