		private void RenderSplitter(float minTreeWidth, float maxTreeWidth, float height, float splitterWidth)
		{
			// ??????? ???????? ?? ??? ?????? ?????? (??? ? ??????, ????????????/??????? ??????? -
			// ???? ? ??? ?? ?????????????, ??? ?????????? "?????"/????????? ?????), ?? ??
