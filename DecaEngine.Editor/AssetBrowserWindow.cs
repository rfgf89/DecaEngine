			/// </summary>
			public AssetEntry(string parentModelPath, string subMeshName, int subMeshIndex)
			{
				FullPath = $"{parentModelPath}::sub{subMeshIndex}";
				Name = subMeshName;
				IsDirectory = false;
				IsEmptyDirectory = false;
				SubMeshIndex = subMeshIndex;
				ParentModelPath = parentModelPath;
			}
		}

