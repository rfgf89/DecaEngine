		private static Entity ResolveAttachPoint(EntityStore store, Entity? parent)
		{
			if (parent.HasValue)
			{
				return parent.Value;
			}
			if (!store.StoreRoot.IsNull)
			{
				return store.StoreRoot;
			}
			var root = store.CreateEntity();
			store.SetStoreRoot(root);
			return root;
		}

		/// <summary>
		/// ?????? ????????????? ????, ??? pid ?? ??????????? ?? ? ???? <see cref="DataEntity.children"/> ?
		/// ?.?. ?????? ?????????, ???????????? ????? <see cref="SaveJson"/>.
		/// </summary>
		private static int FindRootIndex(List<DataEntity> list)
		{
			var childPids = new HashSet<long>();
			foreach (var de in list)
			{
				if (de.children == null)
				{
					continue;
				}
				foreach (var c in de.children)
				{
					childPids.Add(c);
				}
			}
			for (int i = 0; i < list.Count; i++)
			{
				if (!childPids.Contains(list[i].pid))
				{
					return i;
				}
			}
			return 0;
		}

		/// <summary>
		/// ????????????? ?????? ?? ????????? ??????? (?????? <c>"$prefab"</c> ??????
		/// <see cref="DataEntity.components"/>) ????? ? ??????? ?????? <paramref name="list"/>:
		/// ?????????? ????, ??????? pid-? ?? ????????? ????????, ????????? overrides ? ???????????
		/// ?????????????? ?????? ?????????? ??????? ??? ??????? ????-??????.
		/// </summary>
		/// <remarks>
		/// ?????? ??????? (???? ?????? JSON-??????? "components" anchor-????????, ????? ?????????????
		/// ? ??????? ????????? ???????????? ???? ?? ????????):
		/// <code>
		/// "components": {
		///   "$prefab": {
		///     "path": "weapon.prefab.json",   // ???????????? ???????? ???????? ?????
		///     "remove": false,                 // true =&gt; ????????? ??????? ??????????? ?????????
		///     "overrides": { "pos": { "x": 9, "y": 9, "z": 9 } } // ???? ?????? ????? ?????????? ???????
		///   }
		/// }
		/// </code>
		/// </remarks>
		private static void ResolveNestedPrefabs(List<DataEntity> list, string baseDir, ref long syntheticPid)
		{
			// list.Count ???????? ?? ?????? ????????: ????? (??? ???????????) ???? ????????????
			// ? ????? ? ?? ???????? "$prefab", ??????? ?? ??????????.
			for (int i = 0; i < list.Count; i++)
			{
				var de = list[i];
				if (de.components.IsNull())
				{
					continue;
				}

				using var compDoc = JsonDocument.Parse(de.components.AsByteArray());
				if (!compDoc.RootElement.TryGetProperty(PrefabRefKey, out var prefabRef))
				{
					continue;
				}

				var relPath = prefabRef.TryGetProperty("path", out var pathEl) ? pathEl.GetString() : null;
				if (string.IsNullOrEmpty(relPath))
				{
					continue;
				}
				bool remove = prefabRef.TryGetProperty("remove", out var removeEl) && removeEl.ValueKind == JsonValueKind.True;
				JsonElement? overridesEl = prefabRef.TryGetProperty("overrides", out var ov) ? ov : (JsonElement?)null;

				// ??????? "$prefab" ?? components ????? ????, ???????? ?????? ???????? ?????????? (???? ????).
				de.components = RemoveKey(de.components, PrefabRefKey);

				if (remove)
				{
					continue;
				}

				var nestedPath = Path.IsPathRooted(relPath) ? relPath : Path.Combine(baseDir, relPath);
				var nestedBytes = File.ReadAllBytes(nestedPath);
				var nestedList = LoadDataEntities(nestedBytes);
				var nestedBaseDir = Path.GetDirectoryName(nestedPath) ?? baseDir;
				ResolveNestedPrefabs(nestedList, nestedBaseDir, ref syntheticPid);

				int nestedRootIndex = FindRootIndex(nestedList);

				// ????? pid-?? ?????????? ?????????, ????? ?? ??????????? ? ??? ???????? ? list.
				var pidMap = new Dictionary<long, long>(nestedList.Count);
				foreach (var n in nestedList)
				{
					pidMap[n.pid] = syntheticPid--;
				}
				foreach (var n in nestedList)
				{
					n.pid = pidMap[n.pid];
					if (n.children == null)
					{
						continue;
					}
					for (int c = 0; c < n.children.Count; c++)
					{
						n.children[c] = pidMap[n.children[c]];
					}
				}

				var nestedRoot = nestedList[nestedRootIndex];

				if (overridesEl.HasValue)
				{
					nestedRoot.components = MergeComponents(nestedRoot.components, JsonElementToJsonValue(overridesEl.Value));
				}

				de.children ??= new List<long>();
				de.children.Add(nestedRoot.pid);
				list.AddRange(nestedList);
			}
		}

		/// <summary>??????? ???? ???????? ?????? ?? JSON-??????? ???????????; ???? ?????? ?? ????????, ?????????? null-JsonValue.</summary>
		private static JsonValue RemoveKey(JsonValue json, string key)
		{
			using var doc = JsonDocument.Parse(json.AsByteArray());
			var remaining = doc.RootElement.EnumerateObject().Where(p => p.Name != key).ToList();
			if (remaining.Count == 0)
			{
				return default;
			}
			using var stream = new MemoryStream();
			using (var writer = new Utf8JsonWriter(stream))
			{
				writer.WriteStartObject();
				foreach (var prop in remaining)
				{
					writer.WritePropertyName(prop.Name);
					prop.Value.WriteTo(writer);
				}
				writer.WriteEndObject();
			}
			return new JsonValue(stream.ToArray());
		}

		private static JsonValue JsonElementToJsonValue(JsonElement element)
		{
			using var stream = new MemoryStream();
			using (var writer = new Utf8JsonWriter(stream))
			{
				element.WriteTo(writer);
			}
			return new JsonValue(stream.ToArray());
		}

		/// <summary>??????? ??? JSON-??????? ???????????, ????? <paramref name="overrideJson"/> ?????????.</summary>
		private static JsonValue MergeComponents(JsonValue baseJson, JsonValue overrideJson)
		{
			if (overrideJson.IsNull())
			{
				return baseJson;
			}
			if (baseJson.IsNull())
			{
				return overrideJson;
			}

			using var baseDoc = JsonDocument.Parse(baseJson.AsByteArray());
			using var overrideDoc = JsonDocument.Parse(overrideJson.AsByteArray());

			var merged = new Dictionary<string, JsonElement>();
			foreach (var prop in baseDoc.RootElement.EnumerateObject())
			{
				merged[prop.Name] = prop.Value;
			}
			foreach (var prop in overrideDoc.RootElement.EnumerateObject())
			{
				merged[prop.Name] = prop.Value;
			}

			using var stream = new MemoryStream();
			using (var writer = new Utf8JsonWriter(stream))
			{
				writer.WriteStartObject();
				foreach (var kvp in merged)
				{
					writer.WritePropertyName(kvp.Key);
					kvp.Value.WriteTo(writer);
				}
				writer.WriteEndObject();
			}
			return new JsonValue(stream.ToArray());
		}
