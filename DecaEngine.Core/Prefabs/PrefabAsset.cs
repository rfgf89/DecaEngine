		private static Entity InstantiateFromBytes(EntityStore store, byte[] jsonBytes, string baseDir, Entity? parent)
		{
			var list = LoadDataEntities(jsonBytes);
			if (list.Count == 0)
			{
				throw new InvalidOperationException("Prefab document contains no entities.");
			}

			long syntheticPid = -1_000_000_000L;
			ResolveNestedPrefabs(list, baseDir, ref syntheticPid);

			int rootIndex = FindRootIndex(list);
			Entity attach = ResolveAttachPoint(store, parent);

			AddDataEntitiesResult result = TreeUtils.AddDataEntitiesToEntity(attach, list);
			if (result.errors is { Count: > 0 })
			{
				throw new InvalidOperationException("Prefab instantiate errors: " + string.Join("; ", result.errors));
			}

			// AddDataEntitiesToEntity ?????????????? de.pid/de.children ?????? pid-???
			// ????????? Entity ? ??????? ????? ?????? list[rootIndex].pid ??? ??? ????? pid.
			long newRootPid = list[rootIndex].pid;
			return store.GetEntityByPid(newRootPid);
		}

		private static List<DataEntity> LoadDataEntities(byte[] jsonBytes)
		{
			var json = new JsonValue(jsonBytes);
			var list = new List<DataEntity>();
			var error = TreeUtils.JsonArrayToDataEntities(json, list);
			if (error != null)
			{
				throw new InvalidOperationException($"Failed to parse prefab JSON: {error}");
			}
			return list;
		}

		/// <summary>
