		/// <summary>??????????? ????????? JSON-?????? ? ???????? ????????? ??? ????????/?????.</summary>
		public static void Cook(string jsonPath, string binPath)
		{
			var jsonBytes = File.ReadAllBytes(jsonPath);
			var dir = Path.GetDirectoryName(binPath);
			if (!string.IsNullOrEmpty(dir))
			{
				Directory.CreateDirectory(dir);
			}
			using var fs = File.Create(binPath);
			using var bw = new BinaryWriter(fs);
			bw.Write(BinaryMagic);
			bw.Write(BinaryVersion);
			bw.Write(jsonBytes.Length);
			using (var brotli = new BrotliStream(fs, CompressionLevel.Optimal, leaveOpen: true))
			{
				brotli.Write(jsonBytes, 0, jsonBytes.Length);
			}
		}

		/// <summary>?????? ?????????? ??? "*.prefab.json" ????? ? ?????????? ? ???????? "*.prefab.bin".</summary>
		public static void CookDirectory(string assetsDir, string searchPattern = "*.prefab.json")
		{
			foreach (var jsonPath in Directory.EnumerateFiles(assetsDir, searchPattern, SearchOption.AllDirectories))
			{
				var binPath = Path.ChangeExtension(jsonPath, ".bin");
				Cook(jsonPath, binPath);
			}
		}

		/// <summary>
		/// ???????????? ?????? ?? ????????? (?????? <see cref="Instantiate"/>, ?? ?? "*.prefab.bin").
		/// </summary>
		public static Entity InstantiateBinary(EntityStore store, string binPath, Entity? parent = null)
		{
			using var fs = File.OpenRead(binPath);
			using var br = new BinaryReader(fs);
			var magic = br.ReadBytes(BinaryMagic.Length);
			if (!magic.AsSpan().SequenceEqual(BinaryMagic))
			{
				throw new InvalidDataException($"'{binPath}' is not a valid prefab binary (bad magic).");
			}
			var version = br.ReadInt32();
			if (version != BinaryVersion)
			{
				throw new InvalidDataException($"'{binPath}' has unsupported prefab binary version {version}.");
			}
			var uncompressedLength = br.ReadInt32();
			var jsonBytes = new byte[uncompressedLength];
			using (var brotli = new BrotliStream(fs, CompressionMode.Decompress))
			{
				int offset = 0;
				while (offset < uncompressedLength)
				{
					int read = brotli.Read(jsonBytes, offset, uncompressedLength - offset);
					if (read == 0)
					{
						break;
					}
					offset += read;
				}
			}
			var baseDir = Path.GetDirectoryName(Path.GetFullPath(binPath)) ?? ".";
			return InstantiateFromBytes(store, jsonBytes, baseDir, parent);
		}

